// ========================
// アプリケーション状態管理（グローバルな状態を管理）
// core/app-state.js
// 役割：アプリ全体で共有される状態（データ）を一元管理する
// 特徴：シンプルな状態管理パターン
// ========================

// ================
// 現在のユーザー状態管理
// ================

/**
 * 現在ログインしているユーザーの名前
 * 初期値は "Aさん" に設定
 * この値は以下の場面で使用される：
 * - 支出入力時のデフォルト支払者
 * - ユーザー切替ドロップダウンの初期選択
 * - 清算申請時の申請者
 */
export let currentUser = "Aさん";

/**
 * 現在のユーザーを変更する関数
 * @param {string} u - 新しいユーザー名（"Aさん" または "Bさん"）
 * 
 * 呼び出される場面：
 * - ユーザー切替ドロップダウンが変更された時
 * - アプリ初期化時にデフォルトユーザーを設定する時
 * 
 * 注意：この関数を呼び出すと、アプリ全体のユーザー状態が変更される
 */
export function setCurrentUser(u) {
  currentUser = u;
  // 注意：状態変更後は、通常、関連するUI表示の更新が必要
  // （例：サマリーの再計算、履歴表示の更新など）
}

// ================
// 編集状態管理
// ================

/**
 * 現在編集中の支出データのID
 * 値の意味：
 * - null: 新規入力モード（新しい支出を追加する状態）
 * - 文字列: 編集モード（既存の支出を編集する状態）
 * 
 * この値により、支出入力フォームの動作が変わる：
 * - null の場合：フォーム送信時に新規データとして追加
 * - ID有りの場合：フォーム送信時に既存データを更新
 */
export let editingId = null;

/**
 * 編集中の支出IDを設定する関数
 * @param {string|null} id - 編集する支出のID、または新規作成時は null
 * 
 * 呼び出される場面：
 * - 支出一覧から「編集」ボタンがクリックされた時（IDを設定）
 * - 支出の保存完了後（nullに戻す）
 * - 編集をキャンセルした時（nullに戻す）
 * 
 * 使用例：
 * setEditingId("expense-123"); // 編集モードに切り替え
 * setEditingId(null);          // 新規入力モードに戻す
 */
export function setEditingId(id) {
  editingId = id;
  // この状態変更により、入力フォームの表示内容や動作が変わる
}